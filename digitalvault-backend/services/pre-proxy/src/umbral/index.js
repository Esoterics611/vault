/**
 * Umbral PRE Module
 * Handles proxy re-encryption operations using @nucypher/umbral-pre
 */

const { ethers } = require('ethers');
const logger = require('../utils/logger');
const wrapper = require('./umbral-wrapper');

/**
 * Initialize Umbral library
 */
async function initUmbral() {
  try {
    const loaded = wrapper.loadUmbral();
    if (loaded) {
      logger.info('Umbral PRE library initialized');
      return true;
    } else {
      logger.warn('Umbral PRE not available - install @nucypher/umbral-pre package');
      logger.warn('Service will use mock implementation until Umbral is installed');
      return false;
    }
  } catch (error) {
    logger.error('Failed to initialize Umbral:', error);
    return false;
  }
}

/**
 * Perform proxy re-encryption
 *
 * @param {Object} params
 * @param {Buffer} params.originalCapsule - Original Umbral capsule bytes
 * @param {string} params.granteePublicKey - Grantee's public key (hex)
 * @param {number} params.threshold - Threshold for reconstruction (M)
 * @param {number} params.totalShares - Total number of shares (N)
 * @param {string} [params.kfragData] - Optional: Pre-generated kfrag data from blockchain
 * @returns {Object} Re-encryption result
 */
async function performReencryption({ originalCapsule, granteePublicKey, threshold, totalShares, kfragData }) {
  logger.info('Starting re-encryption', {
    capsuleSize: originalCapsule.length,
    threshold,
    totalShares,
    hasKfrag: !!kfragData
  });

  // Check if Umbral is loaded
  if (!wrapper.isLoaded) {
    logger.warn('Umbral not loaded, using mock implementation');
    return performMockReencryption({ originalCapsule, granteePublicKey, threshold, totalShares });
  }

  try {
    // Parse original capsule
    const capsule = wrapper.parseCapsule(originalCapsule);
    logger.debug('Capsule parsed successfully');

    // Parse grantee public key
    const granteeKey = wrapper.parsePublicKey(granteePublicKey);
    logger.debug('Grantee public key parsed successfully');

    // In production, kfrags come from the marketplace transaction
    // For MVP testing, we'll simulate having pre-generated kfrags
    // In reality, these would be:
    // 1. Generated by content owner when creating the grant
    // 2. Stored on-chain or provided in the purchase transaction
    // 3. Retrieved by the proxy from blockchain/IPFS

    let cfrags;

    if (kfragData) {
      // Use provided kfrags (production scenario)
      logger.info('Using provided kfrags from blockchain');
      // Parse and apply kfrags
      // This would involve deserializing kfrags and applying them
      // Implementation depends on how kfrags are stored on-chain
      throw new Error('Production kfrag application not yet implemented');
    } else {
      // For MVP/testing: simulate re-encryption
      // In production, this branch should never execute
      logger.warn('No kfrags provided - using test re-encryption');

      // Generate test kfrags (only for testing!)
      const testKeys = wrapper.generateTestKeys();

      // Generate kfrags using delegating key
      const kfrags = wrapper.generateKFrags(
        testKeys.delegatingSecretKey,
        granteeKey,
        testKeys.signer,
        threshold,
        totalShares
      );

      logger.debug(`Generated ${kfrags.length} kfrags for testing`);

      // Apply kfrags to capsule to create cfrags
      cfrags = kfrags.map((kfrag, index) => {
        try {
          const cfrag = wrapper.reencrypt(capsule, kfrag);
          logger.debug(`Created cfrag ${index + 1}/${kfrags.length}`);
          return cfrag;
        } catch (error) {
          logger.error(`Failed to create cfrag ${index}:`, error);
          throw error;
        }
      });
    }

    // Serialize cfrags
    const serializedCfrags = cfrags.map((cfrag, index) => ({
      index,
      data: '0x' + wrapper.serializeCFrag(cfrag).toString('hex')
    }));

    // The new capsule is the original capsule with cfrags attached
    // The buyer will use threshold number of cfrags to decrypt
    const newCapsuleData = {
      originalCapsule: wrapper.serializeCapsule(capsule),
      cfrags: serializedCfrags,
      threshold
    };

    // Serialize the complete re-encrypted capsule package
    const newCapsuleBytes = Buffer.from(JSON.stringify(newCapsuleData));
    const newCapsuleHash = ethers.keccak256(newCapsuleBytes);

    logger.info('Re-encryption completed successfully', {
      originalSize: originalCapsule.length,
      cfragCount: cfrags.length,
      threshold
    });

    return {
      newCapsule: '0x' + newCapsuleBytes.toString('hex'),
      newCapsuleHash,
      cfrags: serializedCfrags,
      threshold,
      totalShares
    };
  } catch (error) {
    logger.error('Re-encryption operation failed:', error);
    throw new Error(`Re-encryption failed: ${error.message}`);
  }
}

/**
 * Mock re-encryption for when Umbral is not available
 * Used for development and testing without the Umbral package
 */
function performMockReencryption({ originalCapsule, granteePublicKey, threshold, totalShares }) {
  logger.warn('Using MOCK re-encryption - not suitable for production');

  // Create mock new capsule
  const mockNewCapsule = Buffer.concat([
    originalCapsule,
    Buffer.from('_reencrypted_mock', 'utf8')
  ]);

  // Create mock cfrags
  const mockCfrags = Array(totalShares).fill(null).map((_, i) => ({
    index: i,
    data: `0x${Buffer.from(`mock_cfrag_${i}_${Date.now()}`).toString('hex')}`
  }));

  const newCapsuleHash = ethers.keccak256(mockNewCapsule);

  logger.info('Mock re-encryption completed', {
    originalSize: originalCapsule.length,
    newSize: mockNewCapsule.length,
    cfragCount: mockCfrags.length
  });

  return {
    newCapsule: '0x' + mockNewCapsule.toString('hex'),
    newCapsuleHash,
    cfrags: mockCfrags,
    threshold,
    totalShares,
    isMock: true  // Flag to indicate this is mock data
  };
}

/**
 * Verify a capsule is valid
 * @param {Buffer} capsuleData - Capsule bytes
 * @returns {boolean} True if valid
 */
async function verifyCapsule(capsuleData) {
  if (!wrapper.isLoaded) {
    logger.warn('Umbral not loaded, skipping capsule verification');
    return capsuleData && capsuleData.length > 0;
  }

  try {
    const capsule = wrapper.parseCapsule(capsuleData);

    // Verify capsule structure
    // The actual verification depends on the Umbral API
    if (capsule.verify) {
      return capsule.verify();
    }

    // If no verify method, just check that parsing succeeded
    return true;
  } catch (error) {
    logger.error('Capsule verification failed:', error);
    return false;
  }
}

